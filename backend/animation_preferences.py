"""One channel preference for PNG objects in both editable animation formats."""
import store

QUALITY_RULES = '''
Якість постановки для animation та razgon_2d в усіх універсальних проєктах:
- У задумі кадру вкажи одну головну думку, композиційний центр, послідовність показу й зміст кожного руху.
  Кожна стрілка має конкретну ціль; підпис прив’язаний до свого об’єкта; розмір, опора й перспектива узгоджені.
- Геометрія доречна для справжнього графіка, зв’язку або схеми. Випадковий набір прямокутників, кіл і плашок
  не замінює зрозумілу сцену. Ковдра, тіло й інші конкретні речі мають впізнаваний вигляд та логічний контакт.
  PNG-предмети складають цілісну композицію; обрізана кінцівка, завислий предмет чи незрозуміла склейка є браком.
- Кожна анімація пояснює зміну, причинний зв’язок, напрямок або важливий момент озвучки.
  Спокійний показ для читання допустимий. Не додавай безперервний рух, частинки, сяйво, хитання чи зум заради активності.
- Залиши місце тексту й логотипа, перевір контраст, центр тексту в плашці, поля та всі крайні позиції руху.
  Написи мають достатній час для читання. Шари й ефекти закінчуються на межі своєї сцени.
- Економна перевірка: на кожній партії до 5 кадрів один аркуш старт/основний стан/фінал, додатково лише
  ризиковий момент перекриття або руху. Повторно перевіряй тільки змінені кадри, залежності й сусідні стики.
  Використовуй кеш перевірок. Не рендери MP4, не запускай другого агента й не перечитуй весь ролик заради локальної правки.
'''


def universal(project, settings):
    kind=project.get('project_kind')
    return (kind if kind in {'regular','animated'} else settings.get('channel_kind','regular')) != 'animated'


def people_rules(project, settings):
    if universal(project, settings):
        return ('\nВ універсальному проєкті стримана документальна подача людей діє для всіх форматів, включно з animation та razgon_2d. '
                'Стікмени, дудли й мультяшні ведучі заборонені. Використовуй реалістичні зображення людей або '
                'коректну анатомічну ілюстрацію за змістом; враховуй вік аудиторії. Назва Razgon означає інструмент, '
                'а не дозвіл змінити образ людей. Чужий приклад зі стікменом не переносити в цей канал.\n')
    return ''

TEXT_RULES = ('\nЧитабельність тексту обов’язкова. Заголовки закріплюй у координатах екрана без постійного зуму, хитання чи дрейфу; після короткої появи вони нерухомі. '
              'Підпис предмета може рухатися лише разом із цим предметом в одній групі. Тінь або сяйво не додавай до вже контрастного тексту. '
              'Колір тексту й плашки бери зі спільної палітри вибраного стилю. У світлому стилі не залишай темний текст на старій темній плашці. '
              'До здачі перевір контраст, перекриття й узгоджені межі сусідніх кадрів, зберігаючи прийняті сцени.\n')


def instructions(project, *, planning=False):
    try:
        settings=store.read_json(store.get_channel_folder(project['channel_id'],include_disabled=True)/store.PLAN_CONFIG,{}) or {}
    except (store.StudioError, KeyError, OSError):
        settings={}
    enabled=(settings.get('animation') or {}).get('assets',True) is not False
    rules=QUALITY_RULES+TEXT_RULES+people_rules(project,settings)
    if not enabled:
        return rules+'\nPNG асети вимкнені для animation та razgon_2d. Предмети нових анімацій малюй кодом; не підмінюй це PNG-предметами. Повнокадрові фото мають окремий формат. Наявні прийняті кадри зберігай.\n'
    text='\nPNG асети увімкнені. Це обов’язкова вимога для обох форматів: кодової анімації animation і 2D-анімації razgon_2d, також в універсальному проєкті. Для предметів, органів, людей та інших конкретних об’єктів використовуй доречні готові PNG асети. Геометрію, графіки, схеми й написи можна малювати кодом. Не зводь усі кадри до геометричних замінників предметів.\n'
    if planning:
        return rules+text+'У задумі відповідних кадрів вкажи, який предмет показати PNG асетом, а які частини зробити кодом. На етапі плану лише запиши рішення; створення зображень виконує агент кадрів.\n'
    return rules+text+'''Спершу використай збережені picks і відповідні предмети проєкту, далі один обмежений пошук tools/library.py search і один аркуш кандидатів.
Вдалий предмет підключи через library.py pull; якщо відповідного немає, створи PNG предмет у Codex. Не переглядай бібліотеку повторними довгими колами.
Для animation додай PNG як окремий редагований шар через op=animation, clips з kind=image і path, рух через keyframes. Для PNG підписів передай foreground=true.
Для razgon_2d підключи PNG у scenes/assets.js, реально намалюй їх у сцені й залиш config.json assets=true. Самі завантажені файли без використання в кадрі не виконують вимогу.
Зафіксуй, які PNG взято з бібліотеки або створено й у яких кадрах вони використані. Уже прийняті сцени зберігай.\n'''
